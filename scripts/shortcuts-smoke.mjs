import { _electron as electron } from 'playwright'
import { PDFDocument, StandardFonts } from 'pdf-lib'
import { mkdir, writeFile } from 'node:fs/promises'
import { resolve, join } from 'node:path'
import assert from 'node:assert/strict'

const root = resolve('output/playwright/shortcuts'); await mkdir(root, { recursive: true })
const pdf = await PDFDocument.create(); const font = await pdf.embedFont(StandardFonts.TimesRoman)
for (let n = 1; n <= 5; n++) {
  const sheet = pdf.addPage([600, 800])
  for (let line = 0; line < 28; line++) sheet.drawText(`Page ${n}. Keyboard shortcuts keep reading and annotation convenient. Line ${line + 1}.`, { x: 40, y: 740 - line * 22, size: 12, font })
}
const fixture = join(root, 'paper.pdf'); await writeFile(fixture, await pdf.save())
const translated = join(root, 'translated.pdf')
const other = await PDFDocument.create(); const otherFont = await other.embedFont(StandardFonts.TimesRoman)
for (let n = 1; n <= 5; n++) other.addPage([600, 800]).drawText(`Translated version page ${n}. Text for keyboard selection.`, { x: 40, y: 740, size: 12, font: otherFont })
await writeFile(translated, await other.save())
const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE
const executablePath = process.env.PAPER_READER_EXECUTABLE
const app = await electron.launch({ ...(executablePath ? { executablePath: resolve(executablePath) } : {}), args: [...(executablePath ? [] : ['.']), fixture, `--data-dir=${join(root, `data-${Date.now()}`)}`], env })
let page
try {
  page = await app.firstWindow()
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  await page.locator('.textLayer span').first().waitFor({ timeout: 30000 })
  await page.keyboard.press('F1'); await page.waitForTimeout(100)
  assert.equal(await page.getByRole('dialog', { name: '快捷键' }).count(), 1, 'F1 must open the shortcuts reference')
  await page.keyboard.press('Alt+1')
  assert.equal(await page.getByLabel('阅读模式').inputValue(), 'parallel', 'help must block underlying reader commands')
  for (let n = 0; n < 3; n++) {
    await page.keyboard.press('Tab')
    assert(await page.getByRole('dialog', { name: '快捷键' }).evaluate(dialog => dialog.contains(document.activeElement)), 'Tab must stay inside the help dialog')
  }
  await page.screenshot({ path: join(root, 'help.png') })
  await page.keyboard.press('Escape')
  await page.getByRole('dialog', { name: '快捷键' }).waitFor({ state: 'hidden' })
  assert.equal(await page.getByRole('dialog', { name: '快捷键' }).count(), 0)
  await page.keyboard.press('Alt+1')
  assert.equal(await page.getByLabel('阅读模式').inputValue(), 'original')
  const left = page.locator('[data-side="left"]')
  const reader = left.locator('.pdf-scroll')
  await reader.focus()
  await page.keyboard.press('Control+g')
  assert(await page.getByLabel('左侧页码', { exact: true }).evaluate(input => input === document.activeElement))
  await page.getByLabel('左侧页码', { exact: true }).fill('3')
  await page.keyboard.press('Enter')
  assert(await reader.evaluate(element => document.activeElement === element), 'jumping must return keyboard focus to reading')
  await page.keyboard.press('Control+PageDown')
  assert.equal(await page.getByLabel('左侧页码', { exact: true }).inputValue(), '4')
  await page.keyboard.press('Control+PageUp')
  assert.equal(await page.getByLabel('左侧页码', { exact: true }).inputValue(), '3')
  await page.keyboard.press('Control+=')
  assert.equal(await page.getByLabel('左侧缩放').inputValue(), '1.25')
  await page.keyboard.press('Control+-')
  assert.equal(await page.getByLabel('左侧缩放').inputValue(), '1')
  for (let n = 0; n < 12; n++) await page.keyboard.press('Control+=')
  assert.equal(await page.getByLabel('左侧缩放').inputValue(), '3')
  for (let n = 0; n < 12; n++) await page.keyboard.press('Control+-')
  assert.equal(await page.getByLabel('左侧缩放').inputValue(), '0.5')
  await page.keyboard.press('Control+0')
  assert.equal(await page.getByLabel('左侧缩放').inputValue(), '1')
  assert.equal(await app.browserWindow(page).then(window => window.evaluate(window => window.webContents.getZoomFactor())), 1, 'zoom shortcuts must not zoom the application UI')
  await page.keyboard.press('Control+g')
  await page.keyboard.press('Alt+2')
  assert.equal(await page.getByLabel('阅读模式').inputValue(), 'original', 'reading shortcuts must not run in inputs')
  await page.getByLabel('左侧页码', { exact: true }).fill('1'); await page.keyboard.press('Enter')
  await left.locator('[data-page="1"] .textLayer span').first().waitFor()
  const selectText = async (side = 'left') => {
    const pane = page.locator(`[data-side="${side}"]`)
    await pane.locator('.pdf-scroll').focus()
    await pane.locator('[data-page="1"] .textLayer span').first().evaluate(span => {
      const range = document.createRange(); range.setStart(span.firstChild, 0); range.setEnd(span.firstChild, Math.min(30, span.firstChild.length))
      getSelection().removeAllRanges(); getSelection().addRange(range)
    })
    await pane.locator('.textLayer').first().dispatchEvent('mouseup')
    await page.getByTestId('selection-toolbar').waitFor()
  }
  const marks = async count => page.waitForFunction(count => document.querySelectorAll('.highlight-mark').length === count, count)
  await selectText(); await page.keyboard.press('Alt+h'); await marks(1)
  await page.keyboard.press('Control+z'); await marks(0)
  await selectText(); await page.keyboard.press('Alt+n')
  const note = page.getByRole('textbox', { name: '批注备注', exact: true })
  await note.waitFor(); await note.focus()
  await app.evaluate(({ dialog }) => {
    globalThis.__shortcutOpenCount = 0
    dialog.showOpenDialog = async () => { globalThis.__shortcutOpenCount++; return { canceled: true, filePaths: [] } }
  })
  await page.keyboard.press('Control+o'); await page.waitForTimeout(100)
  assert.equal(await app.evaluate(() => globalThis.__shortcutOpenCount), 1, 'existing Ctrl+O must remain available while an input has focus')
  await note.pressSequentially('native undo')
  await page.keyboard.press('Control+z')
  const afterTextUndo = await note.inputValue()
  assert(afterTextUndo.length < 'native undo'.length && 'native undo'.startsWith(afterTextUndo), 'Ctrl+Z inside a note must use native text undo')
  assert.equal(await page.locator('.highlight-mark').count(), 1, 'native text undo must not remove the annotation')
  await note.fill('kept note')
  await reader.focus()
  await page.getByRole('button', { name: '将批注改为绿色', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('.highlight-mark')?.style.backgroundColor === 'rgb(145, 213, 161)')
  await page.keyboard.press('Control+z')
  await page.waitForFunction(() => document.querySelector('.highlight-mark')?.style.backgroundColor === 'rgb(245, 216, 94)')
  assert.equal(await note.inputValue(), 'kept note', 'undoing color must preserve note text')
  await page.getByRole('button', { name: '删除批注', exact: true }).click(); await marks(0)
  await reader.focus(); await page.keyboard.press('Control+z'); await marks(1)
  assert.equal(await note.inputValue(), 'kept note', 'undoing deletion must restore note content')
  await reader.focus(); await page.keyboard.press('Control+z')
  await page.waitForFunction(() => document.querySelector('textarea[aria-label="批注备注"]')?.value === '')
  await reader.focus(); await page.keyboard.press('Control+z'); await marks(0)
  await page.keyboard.press('Escape')
  await selectText(); await page.keyboard.press('Alt+h'); await page.keyboard.press('Control+z')
  await page.waitForFunction(() => !document.querySelector('.status-bar')?.textContent.includes('正在保存批注'))
  await marks(0)
  await page.keyboard.press('Control+Shift+o')
  await page.getByRole('dialog', { name: '导入对照论文' }).waitFor()
  await app.evaluate(({ dialog }, path) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [path] }) }, translated)
  await page.getByRole('dialog').getByRole('button', { name: '选择右侧 PDF', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: '开始对照阅读', exact: true }).click()
  await page.locator('[data-side="right"] .textLayer span').first().waitFor()
  if (await page.getByRole('button', { name: '联动阅读', exact: true }).getAttribute('aria-pressed') === 'true') {
    await reader.focus(); await page.keyboard.press('Alt+l')
  }
  const right = page.locator('[data-side="right"]')
  await reader.focus()
  await right.locator('.pdf-scroll').dispatchEvent('wheel', { deltaY: 40, bubbles: true })
  await page.keyboard.press('Control+g')
  assert(await page.getByLabel('右侧页码', { exact: true }).evaluate(input => document.activeElement === input), 'wheel interaction must make the right pane active even while focus was on the left')
  await right.locator('.pdf-scroll').focus(); await page.keyboard.press('Control+g')
  assert(await page.getByLabel('右侧页码', { exact: true }).evaluate(input => document.activeElement === input))
  await page.getByLabel('右侧页码', { exact: true }).fill('4'); await page.keyboard.press('Enter')
  assert.equal(await page.getByLabel('左侧页码', { exact: true }).inputValue(), '1', 'independent right-page navigation must not move the left pane')
  await page.keyboard.press('Control+=')
  assert.equal(await page.getByLabel('右侧缩放').inputValue(), '1.25')
  assert.equal(await page.getByLabel('左侧缩放').inputValue(), '1')
  await page.keyboard.press('Alt+l'); await page.keyboard.press('Control+=')
  assert.equal(await page.getByLabel('右侧缩放').inputValue(), await page.getByLabel('左侧缩放').inputValue(), 'linked zoom must affect both panes')
  await page.keyboard.press('Alt+3'); assert.equal(await page.getByLabel('阅读模式').inputValue(), 'translated')
  await page.keyboard.press('Alt+1'); assert.equal(await page.getByLabel('阅读模式').inputValue(), 'original')
  await selectText(); await page.keyboard.press('Alt+q')
  await page.getByLabel('论文问答侧栏').waitFor()
  await page.keyboard.press('Escape')
  await reader.focus(); await page.keyboard.press('Control+,')
  await page.getByRole('dialog', { name: 'API 设置' }).waitFor()
  await page.keyboard.press('Alt+2')
  assert.equal(await page.getByLabel('阅读模式').inputValue(), 'original', 'settings must block reader shortcuts')
  await page.keyboard.press('Escape')
  await reader.focus(); await page.keyboard.press('Alt+a')
  await page.getByLabel('批注侧栏', { exact: true }).waitFor()
  await page.keyboard.press('Alt+a')
  await page.getByLabel('批注侧栏', { exact: true }).waitFor({ state: 'hidden' })
  assert.equal(await page.getByLabel('批注侧栏', { exact: true }).isVisible(), false)
  await page.getByRole('button', { name: '快捷键', exact: true }).click()
  await page.getByRole('dialog', { name: '快捷键' }).waitFor()
  await page.keyboard.press('F1')
  await page.getByRole('dialog', { name: '快捷键' }).waitFor({ state: 'hidden' })
  assert(await page.getByRole('button', { name: '快捷键', exact: true }).evaluate(button => document.activeElement === button), 'closing help must restore focus')
  await app.browserWindow(page).then(window => window.evaluate(window => window.setContentSize(960, 680)))
  await page.keyboard.press('F1'); await page.screenshot({ path: join(root, 'help-compact.png') }); await page.keyboard.press('Escape')
  await selectText(); await page.keyboard.press('Alt+h'); await marks(1)
  await app.evaluate(({ dialog }, path) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [path] }) }, translated)
  await reader.focus(); await page.keyboard.press('Control+o')
  await page.waitForFunction(path => document.querySelector('.document-title span[title]')?.title === path, translated)
  await page.locator('[data-side="left"] .textLayer span').first().waitFor()
  await page.locator('[data-side="left"] .pdf-scroll').focus(); await page.keyboard.press('Control+z'); await marks(0)
  await app.evaluate(({ dialog }, path) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [path] }) }, fixture)
  await page.keyboard.press('Control+o')
  await page.waitForFunction(path => document.querySelector('.document-title span[title]')?.title === path, fixture)
  await marks(1)
  await page.locator('[data-side="left"] .pdf-scroll').focus(); await page.keyboard.press('Control+z')
  assert.equal(await page.locator('.highlight-mark').count(), 1, 'switching documents must clear session undo history')
  assert.deepEqual(errors, [])
  await writeFile(join(root, 'result.json'), JSON.stringify({ passed: true, errors }, null, 2))
  console.log(`Reader shortcut and Ctrl+Z checks passed: ${root}`)
} catch (error) {
  await page?.screenshot({ path: join(root, 'failure.png') }).catch(() => {})
  throw error
} finally { await app.close() }
